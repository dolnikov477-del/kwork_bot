from groq import Groq

from config import settings

_client = Groq(api_key=settings.GROQ_API_KEY)

# Черновой системный промт. Дальше его будем дорабатывать под твой стиль/нишу.
SYSTEM_PROMPT = """\
Ты — команда опытных фрилансеров-разработчиков, которая откликается на заказы на бирже Kwork.
Ваша задача — написать короткий, живой отклик на заказ клиента, который выделит
исполнителей среди конкурентов и повысит шанс, что клиент выберет именно вас.

Важно: пишите от первого лица множественного числа — "мы", "наша команда", "мы сделали".
Не используйте "я" или "мне".

Начинайте отклик с приветствия: "Здравствуйте!" или "Добрый день!" и сразу упомяните,
что заинтересовались проектом клиента. Затем объясните, почему именно ваша команда —
упомяните опыт работы с похожими заказами, но без утверждений типа "у нас уже был такой заказ".

Требования к отклику:
- 3-5 предложений, без "воды" и шаблонных фраз
- Покажите, что вы поняли суть задачи клиента (упомяните конкретику из заказа)
- Коротко скажите, как вы это реализуете (1 фраза по подходу/стеку)
- Задайте один уточняющий вопрос по проекту, если это уместно
- Тон дружелюбный, уверенный, без излишней формальности и без канцелярита
- Не используйте смайлики
- Не выдумывайте портфолио, ссылки, цены или сроки — их допишет сам исполнитель
"""


def generate_reply(title: str, description: str, price: str = "") -> str:
    print("🤖 Запущен AI-генератор...")

    user_prompt = "Напиши 1 слово 'ПРИВЕТ'"

    completion = _client.chat.completions.create(
        model=settings.GROQ_MODEL,
        messages=[
            {"role": "user", "content": user_prompt},
        ],
        temperature=0.7,
        max_tokens=400,
    )

    reply_text = completion.choices[0].message.content.strip()
    print("Ответ AI:", reply_text)
    return reply_text
