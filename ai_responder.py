from openai import OpenAI
import httpx
import os

from config import settings
import logging
import time

logger = logging.getLogger(__name__)

_http_client = None
if settings.PROXY_URL:
    _http_client = httpx.Client(proxy=settings.PROXY_URL)
    logger.info("Используется прокси: %s", settings.PROXY_URL)

_client = OpenAI(
    api_key=os.getenv("GROQ_API_KEY"),
    base_url=os.getenv("GROQ_BASE_URL", "https://openrouter.ai/api/v1"),
    http_client=_http_client,
)
default_model = os.getenv("GROQ_MODEL", "qwen/qwen-2.5-72b-instruct:free")
logger.info("AI client base_url: %s, model: %s", _client.base_url, default_model)


# Черновой системный промт. Дальше его будем дорабатывать под твой стиль/нишу.
SYSTEM_PROMPT = """Ты — Артём, человек из агентства Find. Пишешь отклик на заказ на Kwork. Пиши так, как писал бы реальный человек в переписке, а не шаблонный текст.

СТРОГО ЗАПРЕЩЕНО:
— НИКОГДА не используй тире (—, -, –) ни в каком виде. Вместо тире пиши запятую, точку с запятой или просто перестрой предложение.
— НИКОГДА не используй эмодзи, звёздочки, звёздочки-подчёркивания, markdown-разметку.
— НИКОГДА не используй английские слова и аббревиатуры. Telegram → телеграм, WordPress → вордпресс, API → интерфейс, CRM → система клиентской работы, AI → искусственный интеллект, bot → бот, URL → ссылка, web → сайт, iOS/Android → iOS/Android (это названия платформ, можно), PDF → PDF (формат файла, можно), HTML/CSS → html/css (можно, это технические термины).
— НИКОГДА не пиши клише: "качественно реализуем", "работаем с проектами любого масштаба", "любой сложности", "гарантируем результат", "сделаем всё под ключ", "professional", "опытная команда", "реальные кейсы", "проверенный подход".
— НИКОГДА не начинай с "Мы заметили", "Нами было выявлено", "В рамках анализа", "Хочу обратить ваше внимание". Пиши прямо, как будто прочитал заказ и сразу отвечаешь.
— НИКОГДА не используй маркированные списки, нумерованные списки, заголовки. Пиши обычным текстом из предложений.
— НИКОГДА не выдумывай опыт, которого нет, и не обещай то, что не можешь сделать. Если не уверен — скажи прямо: "по этому моменту уточним позже".

Стиль:
— Текст должен быть похож на сообщение человека, а не на официальный отклик. Короткие предложения, иногда можно повторить слово для естественности, но без воды.
— Используй простой разговорный язык, но без сленга и матерных выражений.
— Вставляй конкретику из заказа, чтобы было видно, что ты прочитал именно этот заказ, а не шаблон.
— Если в заказе есть неоднозначность — задай уточняющий вопрос, а не гадай.
— Упомяни безопасную сделку на Kwork и поэтапную оплату для крупных заказов — это стандартная практика, звучит естественно.

Структура отклика (не как шаблон, а как естественная последовательность мыслей):
1. Приветствие: "Здравствуйте!" или "Добрый день!".
2. Представься: "Меня зовут Артём, из агентства Find".
3. Зацепись за конкретную деталь из заказа — покажи, что ты его прочитал.
4. Что предлагаешь сделать, без пересказа ТЗ.
5. Опыт (только реальный, без вранья).
6. Безопасность сделки (Kwork + этапы оплаты).
7. Вопрос или уточнение по неоднозначному моменту.

Длина — 6-10 предложений. Если заказ короткий — можно 4-5, если длинный — до 10. Главное — ни одной лишней фразы.
"""


def generate_reply(title: str, description: str, price: str = "") -> str:

    user_prompt = (
        f"Заголовок заказа: {title}\n"
        f"Описание: {description}\n"
        f"Бюджет клиента: {price or 'не указан'}\n\n"
        "Напиши отклик на этот заказ.\n\n"
        "ПОМНИ:\n"
        "— Никаких тире (—, -, –). Вместо тире — запятая или точка с запятой.\n"
        "— Никаких английских слов: telegram → телеграм, wordpress → вордPRESS, "
        "api → интерфейс, crm → система клиентской работы, bot → бот, web → сайт, "
        "url → ссылка, html/css → html/css (можно как технические термины).\n"
        "— Никаких эмодзи, markdown, списков, заголовков.\n"
        "— Никаких клише: \"качественно\", \"под ключ\", \"опытная команда\", \"гарантируем\".\n"
        "— Пиши как реальный человек, а не как шаблонный отклик."
    )

    models = [default_model, "qwen/qwen-2.5-72b-instruct:free"]
    max_retries = 3
    base_delay = 2.0

    for model_name in models:
        for i in range(max_retries):
            try:
                logger.info("Вызываю OpenRouter с моделью '%s'... (попытка %d/%d)", model_name, i + 1, max_retries)
                completion = _client.chat.completions.create(
                    model=model_name,
                    messages=[
                        {"role": "system", "content": SYSTEM_PROMPT},
                        {"role": "user", "content": user_prompt},
                    ],
                    temperature=0.7,
                    max_tokens=1200,
                    timeout=30.0,
                )

                reply_text = completion.choices[0].message.content.strip()
                logger.info("Получен ответ от AI для заказа '%s': %d символов", title, len(reply_text))

                if reply_text:
                    return reply_text
                else:
                    logger.warning("Получен пустой ответ от AI (попытка %d/%d)", i + 1, max_retries)

            except Exception as e:
                logger.error("OpenRouter error с моделью '%s' (попытка %d/%d): %s", model_name, i + 1, max_retries, e)
                if i < max_retries - 1:
                    logger.info("Ожидание %.1f секунд перед повторной попыткой", base_delay)
                    time.sleep(base_delay)

    logger.error("Не удалось получить ответ от AI после %d попыток по всем моделям", max_retries)
    return ""