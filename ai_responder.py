from groq import Groq

from config import settings
import logging
import time

logger = logging.getLogger(__name__)

_client = Groq(api_key=settings.GROQ_API_KEY)

# Черновой системный промт. Дальше его будем дорабатывать под твой стиль/нишу.
SYSTEM_PROMPT = """\
Ты помогаешь составить отклик на заказ фрилансера на бирже Kwork от лица агентства Find (посредник между заказчиком и реальными исполнителями).

СТРОГИЕ ПРАВИЛА:

0. Сначала напиши короткое приветствие: "Здравствуйте!" или "Добрый день!", затем представься: "Меня зовут Артём, из агентства Find". Только после этого переходи к следующим пунктам.

0.1. СТИЛЬ ОБРАЩЕНИЯ:
— Начинай отклик с обычного приветствия: "Здравствуйте!" или 
  "Добрый день!" — без него текст выглядит холодно.
— НЕ используй канцелярские/безличные конструкции вроде "мы заметили, 
  что в вашем ТЗ...", "нами было выявлено...", "в рамках анализа 
  задачи...". Пиши как обычный человек, который прочитал заказ и 
  сразу переходит к сути: "Для бота на распознавание ингредиентов 
  предлагаем..." — без вступительных фраз-прокладок.

1. НИКОГДА не выдумывай и не приписывай опыт, которого нет.
   Используй только опыт из списка: [реальный список: Telegram-боты, 
   парсинг, автоматизация, CRM-интеграции].

2. НЕ обещай источники данных, объёмы или методы работы, если не уверен 
   на 100%, что технически это реально сделать (например: не обещай 
   парсинг с Google Maps, Яндекс поисковой выдачи или закрытых API, 
   если есть шанс блокировки — лучше сразу написать "источники уточним 
   после проверки доступности" вместо конкретного списка).

3. Если в заказе есть неоднозначность (что считать релевантным результатом, 
   какие критерии отбора, какой нужен формат) — ОБЯЗАТЕЛЬНО задай 
   уточняющий вопрос до начала работы, а не после сдачи. Это экономит 
   и наше время, и доверие клиента.

4. НЕ предлагай скидку автоматически. Скидка — ответ на возражение 
   по цене, а не стартовое предложение.

5. Обязательно закрывай вопрос ДОВЕРИЯ: упоминай безопасную сделку 
   Kwork и готовность к поэтапной оплате для крупных заказов.

6. Цепляйся за конкретную деталь из заказа, не пересказывай ТЗ 
   клиента его же словами.

7. Никаких эмодзи-заголовков и клише вроде "качественно реализуем", 
   "любой сложности", "работаем с проектами любого масштаба".

8. Тон при переписке во время работы — не защитный и не конфликтный, 
   даже если клиент просит доработки. Сначала уточнить, что именно 
   не устроило, предложить решение, и только если правки выходят 
   за рамки исходного ТЗ — вежливо обозначить это как доп. объём 
   с отдельной оплатой, без фраз в духе "это не наша вина".

Структура отклика:
— короткое обращение по проекту, представление
— зацепка за конкретную деталь заказа
— что конкретно предлагаем сделать (без пересказа ТЗ)
— реальный опыт (без вранья), с оговоркой по неопределённым источникам
— как устроена безопасность сделки (Kwork + этапы оплаты)
— вопрос заказчику или уточнение неоднозначных моментов

Длина — 6-10 предложений, без воды.
"""


def generate_reply(title: str, description: str, price: str = "") -> str:

    user_prompt = (
        f"Заголовок заказа: {title}\n"
        f"Описание: {description}\n"
        f"Бюджет клиента: {price or 'не указан'}\n\n"
        "Напиши отклик на этот заказ."
    )

    models = [settings.GROQ_MODEL, "qwen/qwen3.6-27b"]
    max_retries = 3
    base_delay = 2.0

    for model in models:
        for i in range(max_retries):
            try:
                logger.info("Вызываю Groq с моделью '%s'... (попытка %d/%d)", model, i + 1, max_retries)
                completion = _client.chat.completions.create(
                    model=model,
                    messages=[
                        {"role": "system", "content": SYSTEM_PROMPT},
                        {"role": "user", "content": user_prompt},
                    ],
                    temperature=0.7,
                    max_tokens=1200,
                    timeout=30.0,
                )

                reply_text = completion.choices[0].message.content.strip()
                logger.info("Получен ответ от AI для заказа '%s': %d символов", title, len(reply_text))

                if reply_text:
                    return reply_text
                else:
                    logger.warning("Получен пустой ответ от AI (попытка %d/%d)", i + 1, max_retries)

            except Exception as e:
                logger.error("Groq error с моделью '%s' (попытка %d/%d): %s", model, i + 1, max_retries, e)
                if i < max_retries - 1:
                    logger.info("Ожидание %.1f секунд перед повторной попыткой", base_delay)
                    time.sleep(base_delay)

    logger.error("Не удалось получить ответ от AI после %d попыток по всем моделям", max_retries)
    return ""